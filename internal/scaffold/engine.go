// GoWorkShell is the base go.work content the engine synthesizes when two or
// more selected plugins each contribute their own Go module. No plugin ships
// this file directly — a single module has nothing to work across, so it's
// only emitted once there's a real reason for it (see mergeGoWork).
const GoWorkShell = "go 1.23\n\nuse (\n\t" + fragment.DefaultMarker + "\n)\n"

// Options configures a single Generate call.
type Options struct {
	// Plugins must already be resolved and validated (requires/conflicts
	// checked) by the caller, in Kind order — Generate applies them in the
	// order given, which determines fragment-merge order.
	Plugins []*plugin.Plugin
	Values  Values
}

// GeneratedFile is one file Generate produced.
type GeneratedFile struct {
	Content    []byte
	Executable bool
}

// Result is Generate's complete output, entirely in memory: every generated
// file, keyed by its "/"-joined path relative to the project root (never an
// OS-specific path — this is also exactly what a zip archive entry name
// looks like). Generate never touches disk; see WriteToDisk.
type Result struct {
	Files map[string]GeneratedFile
}

// Generate copies, renders, and merges every selected plugin's contribution
// into an in-memory Result. It does no I/O — not writing files, not running
// post_copy hooks, not touching disk at all — so it can run anywhere Go can
// run, including compiled to WebAssembly in a browser. Callers that want a
// real project on disk call WriteToDisk and then RunHooks.
func Generate(opts Options) (Result, error) {
	result := Result{Files: map[string]GeneratedFile{}}

	var composeFragments [][]byte
	textFragments := map[string][]fragment.NamedFragment{}
	goModuleCount := 0

	for _, p := range opts.Plugins {
		if p.Manifest.ContributesGoModule {
			goModuleCount++
		}
		if err := copyPluginFiles(p, result.Files, opts.Values); err != nil {
			return Result{}, fmt.Errorf("plugin %s: %w", pluginRef(p), err)
		}
		compose, text, err := collectFragments(p, opts.Values)
		if err != nil {
			return Result{}, fmt.Errorf("plugin %s: %w", pluginRef(p), err)
		}
		if compose != nil {
			composeFragments = append(composeFragments, compose)
		}
		for base, content := range text {
			textFragments[base] = append(textFragments[base], fragment.NamedFragment{
				PluginRef: pluginRef(p),
				Content:   content,
			})
		}
	}

	if len(composeFragments) > 0 {
		merged, err := fragment.MergeCompose(composeFragments)
		if err != nil {
			return Result{}, fmt.Errorf("merging docker-compose fragments: %w", err)
		}
		header := "# Generated by kiln from plugins: " + pluginRefs(opts.Plugins) + "\n"
		result.Files["docker-compose.yml"] = GeneratedFile{Content: append([]byte(header), merged...)}
	}

	// go.work only makes sense once 2+ selected plugins each bring their own
	// Go module — a single module has nothing to work across. The mechanism
	// is built and tested even though it never fires for the current
	// backend+hosting plugin set.
	if frags, ok := textFragments["go.work"]; ok && goModuleCount >= 2 {
		result.Files["go.work"] = GeneratedFile{Content: []byte(GoWorkShell)}
		if err := mergeIntoBase(result.Files, "go.work", frags); err != nil {
			return Result{}, err
		}
	}
	delete(textFragments, "go.work")

	// Every other text fragment target (e.g. Caddyfile, buf.gen.yaml)
	// merges into a base file some plugin already copied into place via
	// files/. Unlike Caddyfile — which always has an owner in practice
	// (hosting ships both the base and its own fragment together) — a
	// target like buf.gen.yaml is genuinely optional: it only exists when
	// a proto-aware plugin (e.g. backend/go-grpc-gateway) was selected, so
	// a fragment aimed at it from an unrelated plugin (e.g. mobile picked
	// without that backend) is simply not applicable and is skipped rather
	// than treated as an error.
	for base, frags := range textFragments {
		if _, ok := result.Files[base]; !ok {
			continue
		}
		if err := mergeIntoBase(result.Files, base, frags); err != nil {
			return Result{}, err
		}
	}

	return result, nil
}

// WriteToDisk persists result under outDir, creating it (and any parent
// directories) if missing.
func WriteToDisk(result Result, outDir string) error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return fmt.Errorf("create output directory: %w", err)
	}
	for relPath, file := range result.Files {
		target := filepath.Join(outDir, filepath.FromSlash(relPath))
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return fmt.Errorf("creating directory for %s: %w", relPath, err)
		}
		mode := os.FileMode(0o644)
		if file.Executable {
			mode = 0o755
		}
		if err := os.WriteFile(target, file.Content, mode); err != nil {
			return fmt.Errorf("writing %s: %w", relPath, err)
		}
	}
	return nil
}

// RunHooks runs each plugin's post_copy script, in selection order, against
// a project already written to outDir (see WriteToDisk) — CLI-only. Never
// call this after a WASM-compiled Generate: there's no real outDir and
// os/exec cannot run in a browser.
func RunHooks(plugins []*plugin.Plugin, outDir string, values Values) error {
	for _, p := range plugins {
		if p.Manifest.PostCopy == "" {
			continue
		}
		if err := runPostCopy(p, outDir, values); err != nil {
			return fmt.Errorf("plugin %s post_copy hook: %w", pluginRef(p), err)
		}
	}
	return nil
}

// copyPluginFiles renders everything under the plugin's files/ directory
// and writes it into dst, keyed by its rendered, transformed relative path
// (see transformPath), flagging executable ones per the plugin's
// Executable globs.
func copyPluginFiles(p *plugin.Plugin, dst map[string]GeneratedFile, values Values) error {
	const root = "files"

	if _, err := fs.Stat(p.FS, root); err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil
		}
		return fmt.Errorf("stat %s: %w", root, err)
	}

	return fs.WalkDir(p.FS, root, func(fp string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || fp == root {
			return err
		}
		rel, err := filepath.Rel(root, fp)
		if err != nil {
			return err
		}
		renderedRel := transformPath(rel, values)

		raw, err := fs.ReadFile(p.FS, fp)
		if err != nil {
			return fmt.Errorf("reading %s: %w", fp, err)
		}

		executable := false
		for _, pattern := range p.Manifest.Executable {
			matched, err := path.Match(pattern, renderedRel)
			if err != nil {
				return fmt.Errorf("invalid executable glob %q: %w", pattern, err)
			}
			if matched {
				executable = true
				break
			}
		}

		dst[renderedRel] = GeneratedFile{Content: Render(raw, values), Executable: executable}
		return nil
	})
}

// transformPath renders placeholders in a plugin-relative path and applies
// two filename escapes needed because content is stored in a //go:embed
// tree, which can't hold every filename a generated project needs:
//
//   - a trailing ".tmpl" is stripped. go:embed treats any directory
//     containing its own go.mod as a separate module boundary and silently
//     excludes everything under it — so a plugin's go.mod template must be
//     named "go.mod.tmpl" in files/ to be embeddable at all, and this
//     strips it back to "go.mod" in the generated project.
//   - a "dot__" prefix on a path segment becomes a literal leading ".".
//     go:embed excludes dot-prefixed files by default, so a plugin's
//     ".env.example" must be named "dot__env.example" in files/.
func transformPath(rel string, values Values) string {
	rendered := RenderString(filepath.ToSlash(rel), values)
	parts := strings.Split(rendered, "/")
	for i, seg := range parts {
		seg = strings.TrimSuffix(seg, ".tmpl")
		if after, ok := strings.CutPrefix(seg, "dot__"); ok {
			seg = "." + after
		}
		parts[i] = seg
	}
	return strings.Join(parts, "/")
}

// collectFragments reads and renders every file under the plugin's
// fragments/ directory, sorting each into either the single Compose
// fragment or a named text fragment keyed by the base file it targets
// (e.g. "Caddyfile.fragment" -> "Caddyfile").
func collectFragments(p *plugin.Plugin, values Values) (compose []byte, text map[string]string, err error) {
	const root = "fragments"

	entries, err := fs.ReadDir(p.FS, root)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil, nil, nil
		}
		return nil, nil, fmt.Errorf("reading fragments dir: %w", err)
	}

	text = map[string]string{}
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		raw, err := fs.ReadFile(p.FS, path.Join(root, e.Name()))
		if err != nil {
			return nil, nil, fmt.Errorf("reading fragment %s: %w", e.Name(), err)
		}
		rendered := Render(raw, values)

		switch {
		case e.Name() == "docker-compose.fragment.yml":
			compose = rendered
		case strings.HasSuffix(e.Name(), ".fragment"):
			base := strings.TrimSuffix(e.Name(), ".fragment")
			text[base] = string(rendered)
		default:
			return nil, nil, fmt.Errorf(
				"unrecognized fragment file %q (expected docker-compose.fragment.yml or <Base>.fragment)", e.Name())
		}
	}
	return compose, text, nil
}

func mergeIntoBase(files map[string]GeneratedFile, baseName string, frags []fragment.NamedFragment) error {
	base, ok := files[baseName]
	if !ok {
		return fmt.Errorf("merging fragments into %s: expected a plugin to have copied it first", baseName)
	}
	merged, err := fragment.MergeTextBlocks(base.Content, fragment.DefaultMarker, frags)
	if err != nil {
		return fmt.Errorf("merging fragments into %s: %w", baseName, err)
	}
	base.Content = merged
	files[baseName] = base
	return nil
}

func runPostCopy(p *plugin.Plugin, outDir string, values Values) error {
	raw, err := fs.ReadFile(p.FS, p.Manifest.PostCopy)
	if err != nil {
		return fmt.Errorf("reading post_copy script: %w", err)
	}

	tmp, err := os.CreateTemp("", "kiln-postcopy-*.sh")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(raw); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmp.Name(), 0o755); err != nil {
		return err
	}

	cmd := exec.Command("sh", tmp.Name())
	cmd.Dir = outDir
	cmd.Env = os.Environ()
	for k, v := range values {
		cmd.Env = append(cmd.Env, "KILN_"+k+"="+v)
	}
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("%w\n%s", err, out)
	}
	return nil
}

func pluginRef(p *plugin.Plugin) string {
	return string(p.Manifest.Kind) + "/" + p.Manifest.Name
}

func pluginRefs(plugins []*plugin.Plugin) string {
	refs := make([]string, len(plugins))
	for i, p := range plugins {
		refs[i] = pluginRef(p)
	}
	return strings.Join(refs, ", ")
}
